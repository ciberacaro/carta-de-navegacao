		</div>

		<div class="comp-corpo">
			<p class="comp-desc">Comunicar online parece simples — mas é uma das competências mais complexas. O que escrevemos fica, pode ser tirado do contexto, e chega a pessoas que não esperávamos. Comunicar bem no digital é saber escolher o quê, o como, o quando e o para quem.</p>

			<div class="comp-grelha">
				<div class="comp-bloco">
					<h3>O que significa na prática</h3>
					<ul>
						<li>Pensar antes de enviar — o que escrevo pode ficar para sempre</li>
						<li>Verificar antes de partilhar — não espalhar o que não confirmei</li>
						<li>Respeitar a privacidade dos outros (não partilhar fotos sem permissão)</li>
						<li>Adaptar o tom ao contexto (profissional vs. pessoal)</li>
						<li>Reconhecer quando uma conversa online está a tornar-se tóxica</li>
					</ul>
				</div>

				<div class="comp-bloco">
					<h3>Em cada etapa da vida</h3>
					<div class="etapas">
						<div class="etapa">
							<span class="etapa-label">Criança</span>
							<span>Ser amigável nas mensagens; não enviar o que não diria pessoalmente</span>
						</div>
						<div class="etapa">
							<span class="etapa-label">Adolescente</span>
							<span>Não partilhar fotos dos outros sem permissão; cuidado com grupos</span>
						</div>
						<div class="etapa">
							<span class="etapa-label">Adulto</span>
							<span>Verificar antes de partilhar notícias; separar contextos pessoal e profissional</span>
						</div>
						<div class="etapa">
							<span class="etapa-label">Sénior</span>
							<span>Perceber que mensagens de WhatsApp podem ser falsas; verificar com a família</span>
						</div>
					</div>
				</div>
			</div>

			<div class="comp-ferramentas">
				<h3>Boas práticas</h3>
				<div class="ferramentas-lista">
					<div class="ferramenta-item">
						<strong>Regra dos 5 minutos</strong>
						<span>Antes de enviar algo no calor do momento, espera 5 minutos</span>
					</div>
					<div class="ferramenta-item">
						<strong>Regra da avó</strong>
						<span>Antes de publicar, pergunta: "ficaria bem se a minha avó visse isto?"</span>
					</div>
					<div class="ferramenta-item">
						<strong>Teste da fonte</strong>
